// Metric-matched fallback faces for the two web fonts, so the text doesn't
// rewrap when Archivo and Radio Canada arrive after the first paint
// (font-display: swap; CLS on slow connections).
//
//   node tools/font-fallbacks.mjs            rewrite the generated block in src/styles/00-tokens.css
//   node tools/font-fallbacks.mjs --measure  measure the width ratios again in Chromium first
//
// Run it with --measure whenever the font subsets (tools/subset-fonts.py) or
// the weights and stretches the CSS uses change.
//
// One size-adjust can't fit every stretch Archivo is used at (100–125%), so
// the fallback family is split into faces by weight and by font-stretch; the
// browser picks the face for each piece of text. size-adjust is the web
// font's width divided by the local font's (Arial Bold, or its metric twin
// Liberation Sans Bold; Roboto on Android), measured over the site's own
// words. ascent-override and descent-override then undo the scaling, so line
// boxes stay the web font's height.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOKENS = path.join(ROOT, 'src/styles/00-tokens.css');
const START = '/* Fallback faces: generated by tools/font-fallbacks.mjs. Don’t edit by hand. */';
const END = '/* End of the generated fallback faces. */';

const BOLD = ['Arial Bold', 'Arial-BoldMT', 'Liberation Sans Bold', 'LiberationSans-Bold', 'Roboto Bold', 'Roboto-Bold'];
const REGULAR = ['Arial', 'ArialMT', 'Liberation Sans', 'LiberationSans', 'Roboto', 'Roboto-Regular'];

// Vertical metrics of the web fonts (hhea ascent and descent, per 1000 units).
const ARCHIVO = { family: 'Archivo Fallback', ascent: 878, descent: 210 };
const RADIO = { family: 'Radio Canada Fallback', ascent: 945, descent: 255 };

// Archivo: rows are weight ranges (measured at `at`), columns stretch ranges
// (measured at `at`). Values: Archivo's width ÷ Arial Bold's, as a percentage.
const ARCHIVO_WEIGHTS = [
  { range: '500 749', at: 700 },
  { range: '750 849', at: 800 },
  { range: '850 900', at: 900 },
];
const ARCHIVO_STRETCHES = [
  { range: '100% 102%', at: 100 },
  { range: '103% 107%', at: 104 },
  { range: '108% 114%', at: 110 },
  { range: '115% 125%', at: 118 },
];
let ARCHIVO_RATIOS = [
  [97.9, 103.2, 109.4, 119.0],
  [102.9, 107.9, 114.0, 123.0],
  [109.4, 114.2, 120.0, 129.0],
];
// Radio Canada: weight ranges against Arial (regular) or Arial Bold.
let RADIO_FACES = [
  { range: '400 449', at: 400, local: REGULAR, ratio: 103.1 },
  { range: '450 549', at: 500, local: REGULAR, ratio: 105.1 },
  { range: '550 649', at: 600, local: REGULAR, ratio: 106.2 },
  { range: '650 700', at: 700, local: BOLD, ratio: 100.4 },
];

async function measure() {
  const { chromium } = await import('playwright');
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.route('http://fonts.test/**', async (route) => {
    const name = new URL(route.request().url()).pathname.slice(1);
    if (!name) return route.fulfill({ body: '<!doctype html><title>Fonts</title>', contentType: 'text/html' });
    return route.fulfill({ body: await fs.readFile(path.join(ROOT, 'src/public/assets/fonts', name)), contentType: 'font/woff2' });
  });
  // The site's own words: headings, buttons, labels and a paragraph of copy.
  const sample =
    'Opal Quest Lounge Free-to-play social casino games Play Gates of Olympus demo Brilliant Twenty-One Lapidary Wheel Seven Systems ' +
    'Responsible gaming Take a 5-minute break Your balance 1,000 Carats Session 12:34 Daily time limit Reality check Straight answers ' +
    'Slots Table games About Settings Deal for 10 Carats Hit Stand Double Split Spin for 35 Carats How it works Need to talk? ' +
    'Every game uses Carats, a free virtual currency. Nothing pays out, and nothing you play for has real-world value.';
  await page.goto('http://fonts.test/');
  await page.setContent(`<!doctype html><style>
    @font-face{font-family:A;src:url(http://fonts.test/archivo.woff2);font-weight:500 900;font-stretch:100% 125%}
    @font-face{font-family:R;src:url(http://fonts.test/radio-canada.woff2);font-weight:400 700}
    </style><body>`);
  await page.evaluate(
    ({ a, r }) => Promise.all([...a.map((w) => document.fonts.load(`${w} 20px A`)), ...r.map((w) => document.fonts.load(`${w} 20px R`))]),
    { a: ARCHIVO_WEIGHTS.map((w) => w.at), r: RADIO_FACES.map((f) => f.at) },
  );
  // Width of the sample in the web font ÷ its width in Arial, as a percentage.
  const ratio = (family, weight, stretch, base) =>
    page.evaluate(({ sample, family, weight, stretch, base }) => {
      const m = (fam, w, st) => {
        const s = document.createElement('span');
        s.textContent = sample;
        Object.assign(s.style, { position: 'absolute', whiteSpace: 'nowrap', fontFamily: fam, fontWeight: w, fontStretch: `${st}%`, fontSize: '100px' });
        document.body.append(s);
        const x = s.getBoundingClientRect().width;
        s.remove();
        return x;
      };
      return Math.round((m(family, weight, stretch) / m('Arial', base, 100)) * 1000) / 10;
    }, { sample, family, weight, stretch, base });
  ARCHIVO_RATIOS = [];
  for (const w of ARCHIVO_WEIGHTS) {
    const row = [];
    for (const st of ARCHIVO_STRETCHES) row.push(await ratio('A', w.at, st.at, 700));
    ARCHIVO_RATIOS.push(row);
  }
  RADIO_FACES = await Promise.all(RADIO_FACES.map(async (f) => ({ ...f, ratio: await ratio('R', f.at, 100, f.local === BOLD ? 700 : 400) })));
  await browser.close();
}

const pct = (n) => `${Math.round(n * 10) / 10}%`;
const src = (names) => names.map((n) => `local("${n}")`).join(',');
function face(font, { weight, stretch, local, ratio }) {
  const k = ratio / 100;
  return `@font-face{font-family:"${font.family}";src:${src(local)};font-weight:${weight};${stretch ? `font-stretch:${stretch};` : ''}size-adjust:${pct(ratio)};ascent-override:${pct(font.ascent / 10 / k)};descent-override:${pct(font.descent / 10 / k)};line-gap-override:0%}`;
}

if (process.argv.includes('--measure')) await measure();
const lines = [];
ARCHIVO_WEIGHTS.forEach((w, i) =>
  ARCHIVO_STRETCHES.forEach((st, j) => lines.push(face(ARCHIVO, { weight: w.range, stretch: st.range, local: BOLD, ratio: ARCHIVO_RATIOS[i][j] }))),
);
for (const f of RADIO_FACES) lines.push(face(RADIO, { weight: f.range, local: f.local, ratio: f.ratio }));
const block = `${START}\n${lines.join('\n')}\n${END}`;

const css = await fs.readFile(TOKENS, 'utf8');
const a = css.indexOf(START);
const b = css.indexOf(END);
if (a < 0 || b < a) throw new Error(`${path.relative(ROOT, TOKENS)} has no generated block to replace (look for "${START}")`);
await fs.writeFile(TOKENS, css.slice(0, a) + block + css.slice(b + END.length));
console.log(`Wrote ${lines.length} fallback faces to ${path.relative(ROOT, TOKENS)}`);
